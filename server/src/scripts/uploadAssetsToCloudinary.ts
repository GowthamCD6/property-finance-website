  contactHero: CLOUDINARY_ASSETS['contact-hero.webp'],
  emiHero: CLOUDINARY_ASSETS['emi.webp'],
  enquiryHero: CLOUDINARY_ASSETS['enquiry-hero.jpg'],
  faqsHero: CLOUDINARY_ASSETS['faqs-hero.webp'],
  heroPropertyFinance: CLOUDINARY_ASSETS['hero-property-finance.jpg'],
  homeLoan: CLOUDINARY_ASSETS['home-loan.jpg'],
  howItsWork: CLOUDINARY_ASSETS['how-its-work.avif'],
